    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // TODO add your handling code here:
        int selectedRow = jTable1.getSelectedRow();
        
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this,
                    "Please select an item to update",
                    "No selection",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        try {
            int modelIndex = jTable1.convertRowIndexToModel(selectedRow);
            Item currentItem = itemArrayObj.getItem(modelIndex);
            if (currentItem == null) {
                throw new Exception("Select item not found in inventory");
            }
            
            AddItemDialog updateDialog = new AddItemDialog(itemArrayObj);
            updateDialog.setTitle("Update Item");
            updateDialog.setItemFields(currentItem.getItemName(),
                                       currentItem.getquantity(),
                                       currentItem.getdeliveryDate());
            updateDialog.setVisible(true);
            
            if (updateDialog.isUpdated()) {
                Item updatedItem = updateDialog.getUpdatedItem();
                
                boolean success = itemArrayObj.updateItem(modelIndex, updatedItem);

                if (success) {
                    refreshTable();
                    
                    int newViewIndex = jTable1.convertRowIndexToModel(modelIndex);
                    jTable1.setRowSelectionInterval(newViewIndex, newViewIndex);
                    jTable1.scrollRectToVisible(jTable1.getCellRect(newViewIndex, 0, true));
                    
                    JOptionPane.showMessageDialog(this, 
                            "Item updated successfully",
                            "Success",
                            JOptionPane.INFORMATION_MESSAGE);
            } else {
               throw new Exception("Failed to updated item");
            }
            }
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error updating item: " + ex.getMessage(),
                                            "Update Error", JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
        
        try {
            itemArrayObj.saveToFile("Inventory.csv");
        } catch (IOException ex) {}
        
         
    }//GEN-LAST:event_jButton4ActionPerformed

