    private void initializeTable() {
        tableModel = new DefaultTableModel(
                new Object[]{"Index", "Item Name", "Quantity", "Delivery Date"}, 0);
        jTable1.setModel(tableModel);
        refreshTable();
    }
    
    
    private void refreshTable() {
        tableModel.setRowCount(0);
        
        ArrayList<Item> items = itemArrayObj.listItems();
        
        for (int i=0; i<items.size(); i++){
            Item item = items.get(i);
            tableModel.addRow(new Object[] {
                i + 1,
                item.getItemName(),
                item.getquantity(),
                item.getdeliveryDate()
            });
        }
        
        if (!items.isEmpty()) {
            int lastRow = tableModel.getRowCount() - 1;
            jTable1.setRowSelectionInterval(lastRow, lastRow);
            jTable1.scrollRectToVisible(jTable1.getCellRect(lastRow, 0, true));
        }
    }
    

    

