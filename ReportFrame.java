    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        if (inventory.listItems().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "No items in inventory to generate report!",
                    "Empty Inventory",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        WeeklyReport weeklyReport = new WeeklyReport();
        StringBuilder report = new StringBuilder("\n=== WEEKLY INVENTORY REPORT ====\n");
        report.append("Generated on: ").append(java.time.LocalDate.now()).append("\n\n");
        report.append(String.format("%-30s %-15s %-15s\n", "Item Name", "Quantity", "Status"));
        report.append("----------------------------------------------------------------------------\n");
        
        for (Item item : inventory.listItems()) {
            String status = weeklyReport.checkStockStatus(item);
            report.append(String.format("%-30s %-15s %-15s\n",
                    item.getItemName(),
                    item.getquantity(),
                    status));
        }
        
        report.append("\n\n ==== SUMMARY ===      \n");
        report.append("Total Items:             ").append(inventory.listItems().size()).append("\n");
        report.append("Low Stock Items:    ").append(weeklyReport.getLowStockCount(inventory)).append("\n");
        report.append("Out of Stock Items: ").append(weeklyReport.getLowStockCount(inventory)).append("\n");
        
        jTextArea2.setText(report.toString());
        
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        if (inventory.listItems().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "No items in inventory to generate report!",
                    "Empty Inventory",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        MonthlyReport monthlyReport = new MonthlyReport();
        StringBuilder report = new StringBuilder("=== MONTHLY INVENTORY REPORT ====\n");
        report.append("Generated on: ").append(java.time.LocalDate.now()).append("\n\n");
        report.append("Reporting Period: ").append(java.time.LocalDate.now().minusMonths(1))
                 .append(" to ").append(java.time.LocalDate.now()).append("\n\n");
        report.append(String.format("%-30s %-15s %-15s\n", "Item Name", "Quantity", "Status"));
        report.append("----------------------------------------------------------------------------\n");
        
        for (Item item : inventory.listItems()) {
            String status = monthlyReport.checkStockStatus(item);
            report.append(String.format("%-30s %-15s %-15s\n",
                    item.getItemName(),
                    item.getquantity(),
                    status));
        }
        
        report.append("\n==== SUMMARY ===\n");
        report.append("Total Items:            ").append(inventory.listItems().size()).append("\n");
        report.append("Low Stock Items:        ").append(monthlyReport.getLowStockCount(inventory)).append("\n");
        report.append("Out of Stock Items:     ").append(monthlyReport.getLowStockCount(inventory)).append("\n");
        report.append("Items to Reorder:       ").append(monthlyReport.getReorderRecommendataions(inventory).size()).append("\n");
        
        
        jTextArea2.setText(report.toString());
    }//GEN-LAST:event_jButton2ActionPerformed

